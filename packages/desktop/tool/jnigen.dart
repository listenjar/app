// Regenerates the JNI bindings Dart calls the app's Java helpers through, one
// file per class: lib/apk_installer.g.dart (ApkInstaller.java, for
// lib/apk_updates.dart) and lib/shared_links.g.dart (SharedLinks.java, for
// lib/shared_links.dart). `moon run desktop:jnigen` after changing either.
// JNIgen reads the Java source and asks the app's Gradle build for the
// Android SDK's classpath.
//
// JNIgen's ApiSummarizer is a Gradle build of its own whose plugins resolve
// from Maven Central, which turns some networks away; this builds it once
// with tool/maven-mirror.gradle (Google's repositories only) and hands
// JNIgen the jar.
import 'dart:io';
import 'dart:isolate';

import 'package:jnigen/jnigen.dart';

Future<void> main() async {
  final root = Platform.script.resolve('../');
  final summarizer = File.fromUri(root.resolve('.dart_tool/jnigen/ApiSummarizer.jar'));
  if (!summarizer.existsSync()) await _buildSummarizer(summarizer, root.resolve('../../tool/maven-mirror.gradle'));
  for (final (java, dart) in _bindings) {
    await JniGenerator(
      input: Input(
        classes: ['com.listenjar.desktop.$java'],
        sourcePath: [root.resolve('android/app/src/main/java/')],
        androidSdk: AndroidSdk(addGradleDeps: true, androidExample: root),
        summarizerCommand: 'java -jar ${summarizer.path}',
      ),
      output: Output(
        dart: DartOutput(path: root.resolve('lib/$dart'), structure: OutputStructure.singleFile),
        preamble: '// Generated by tool/jnigen.dart from $java.java. Do not edit.',
        format: false,
      ),
    ).generate();
  }
}

/// Each Java class in com.listenjar.desktop, and the file under lib/ its
/// bindings go to.
const _bindings = [
  ('ApkInstaller', 'apk_installer.g.dart'),
  ('SharedLinks', 'shared_links.g.dart'),
];

Future<void> _buildSummarizer(File jar, Uri mirror) async {
  final jnigen = await Isolate.resolvePackageUri(Uri.parse('package:jnigen/jnigen.dart'));
  final java = jnigen!.resolve('../java/');
  final gradlew = java.resolve(Platform.isWindows ? 'gradlew.bat' : 'gradlew').toFilePath();
  final build = await Process.run(
    gradlew,
    ['-p', java.toFilePath(), '-I', mirror.toFilePath(), 'buildFatJar', '-x', 'test', '-q'],
    runInShell: true,
  );
  if (build.exitCode != 0) throw StateError('ApiSummarizer failed to build:\n${build.stdout}${build.stderr}');
  await jar.parent.create(recursive: true);
  File.fromUri(java.resolve('build/libs/ApiSummarizer.jar')).copySync(jar.path);
}
