// Regenerates lib/shared_links_ios.g.dart, the Objective-C bindings
// lib/shared_links.dart calls ios/Runner/SharedLinks.swift through:
// `moon run desktop:ffigen-ios` after changing that file. swiftc writes the
// class's Objective-C header, as the app's build would, and FFIgen reads it.
import 'dart:io';

import 'package:ffigen/ffigen.dart';

Future<void> main() async {
  final root = Platform.script.resolve('../');
  final header = File.fromUri(root.resolve('.dart_tool/ffigen/SharedLinks-Swift.h'));
  await header.parent.create(recursive: true);
  final sdk = (await _run('xcrun', ['--sdk', 'iphoneos', '--show-sdk-path'])).trim();
  await _run('xcrun', [
    '--sdk', 'iphoneos', 'swiftc', '-typecheck', '-parse-as-library',
    '-target', 'arm64-apple-ios$_ios',
    '-module-name', 'Runner',
    '-emit-objc-header-path', header.path,
    root.resolve('ios/Runner/SharedLinks.swift').toFilePath(),
  ]);
  await FfiGenerator(
    input: Input(
      entryPoints: [header.uri],
      compilerOptions: ['-x', 'objective-c', '-fobjc-arc', '-isysroot', sdk, '-target', 'arm64-apple-ios$_ios'],
    ),
    objectiveC: ObjectiveC(externalVersions: ExternalVersions(ios: Versions(min: Version(int.parse(_ios), 0, 0)))),
    output: Output(
      dart: DartOutput(path: root.resolve('lib/shared_links_ios.g.dart')),
      // FFIgen writes this only for blocks, which SharedLinks avoids: the app
      // would have to compile it.
      objectiveCFile: root.resolve('.dart_tool/ffigen/shared_links_ios.g.m'),
      preamble: '// Generated by tool/ffigen.dart from ios/Runner/SharedLinks.swift. Do not edit.',
      format: false,
    ),
    visitors: [Visitor(objCInterface: (node) => node.isIncluded = node.originalName == 'LJSharedLinks')],
  ).generate();
}

/// The Runner target's IPHONEOS_DEPLOYMENT_TARGET.
const _ios = '18';

Future<String> _run(String command, List<String> arguments) async {
  final result = await Process.run(command, arguments);
  if (result.exitCode != 0) throw StateError('$command ${arguments.join(' ')} failed:\n${result.stdout}${result.stderr}');
  return result.stdout as String;
}
