import 'dart:io';

import 'package:ffigen/ffigen.dart';

/// Generates lib/src/bindings.g.dart from native/bridge.h:
/// `moon run desktop:ffigen`.
Future<void> main() async {
  final root = Platform.script.resolve('../');
  await FfiGenerator(
    output: Output(
      dart: DartOutput(path: root.resolve('lib/src/bindings.g.dart')),
      preamble: '// Generated by tool/ffigen.dart from native/bridge.h. Do not edit.',
      format: false,
      // Resolved from the code asset hook/build.dart builds.
      style: NativeExternalBindings(assetId: 'package:youtubei/src/bindings.g.dart'),
    ),
    input: Input(entryPoints: [root.resolve('native/bridge.h')]),
    visitors: [
      Visitor(
        func: (node) => node.isIncluded = node.name.startsWith('yt_'),
        struct: (node) => node.isIncluded = node.name.startsWith('Yt'),
        typealias: (node) => node.isIncluded = node.name.startsWith('Yt') ? TypealiasInclude.ifUsed : TypealiasInclude.never,
      ),
    ],
  ).generate();
}
