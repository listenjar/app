// Writes native/scripts.g.c: the scripts yt_load evaluates (host.js, the
// YouTube.js bundle, bindings.js) as C string literals, each zero-terminated
// as JS_Eval requires, so any C compiler builds them in. Its first lines are
// each script's SHA-256, which the build hook checks against the scripts.
// Run by `moon run desktop:scripts`, which caches it on the scripts.
import {createHash} from 'node:crypto';
import {readFileSync, writeFileSync} from 'node:fs';

const native = new URL('../native/', import.meta.url);
const scripts = [['host.js', 'yt_host_js'], ['youtubejs.js', 'yt_youtubejs_js'], ['bindings.js', 'yt_bindings_js']];

const literal = bytes => {
  const lines = [];
  let line = '';
  for (const b of bytes) {
    if (b === 0x22) line += '\\"';
    else if (b === 0x5c) line += '\\\\';
    else if (b === 0x3f) line += '\\?'; // no trigraphs
    else if (b >= 0x20 && b < 0x7f) line += String.fromCharCode(b);
    else line += '\\' + b.toString(8).padStart(3, '0');
    if (b === 0x0a || line.length >= 4000) {
      lines.push(`  "${line}"`);
      line = '';
    }
  }
  if (line || lines.length === 0) lines.push(`  "${line}"`);
  return lines.join('\n');
};

const sources = scripts.map(([file, name]) => ({file, name, bytes: readFileSync(new URL(file, native))}));
const out = [
  ...sources.map(s => `// sha256 ${createHash('sha256').update(s.bytes).digest('hex')} ${s.file}`),
  '// Generated by tool/scripts.mjs (`moon run desktop:scripts`); do not edit.',
  '#include <stddef.h>',
  '',
  ...sources.flatMap(s => [
    `const unsigned char ${s.name}[] =\n${literal(s.bytes)};`,
    `const size_t ${s.name}_len = sizeof(${s.name}) - 1;`,
    '',
  ]),
];
writeFileSync(new URL('scripts.g.c', native), out.join('\n'));
